import type { SessionMessage } from '@anthropic-ai/claude-agent-sdk';
import assert from 'assert';
import { ensureNoDisposablesAreLeakedInTestSuite } from '../../../../base/test/common/utils.js';
import { URI } from '../../../../base/common/uri.js';
import { NullLogService } from '../../../log/common/log.js';
import { ResponsePartKind } from '../../common/state/protocol/state.js';
import { expandCompactedHistory, parseClaudeTranscript, startsAtCompaction } from '../../node/claude/claudeCompactedHistory.js';
import { mapSessionMessagesToTurns } from '../../node/claude/claudeReplayMapper.js';

suite('claudeCompactedHistory', () => {

	ensureNoDisposablesAreLeakedInTestSuite();

	const sessionId = 'a24324bf-0541-4ae2-8ee5-80ec5d3878be';
	const summary = 'This session is being continued from a previous conversation that ran out of context. The summary below covers the earlier portion of the conversation.\n\nSummary:\nThe user said hello.\n\nContinue the conversation from where it left off without asking the user any further questions.';

	/** A transcript shaped like the one the Claude CLI writes for a chat compacted with `/compact`, plus one turn after it. */
	const transcript = [
		{ type: 'queue-operation', operation: 'enqueue', sessionId },
		{ parentUuid: null, isSidechain: false, type: 'user', message: { role: 'user', content: [{ type: 'text', text: 'Say hello' }] }, uuid: 'request_1', timestamp: '2026-10-11T12:35:37.330Z', sessionId },
		{ parentUuid: 'request_1', isSidechain: false, type: 'attachment', attachment: { type: 'prompt_snapshot' }, uuid: 'att-1', sessionId },
		{ parentUuid: 'att-1', isSidechain: false, type: 'assistant', message: { id: 'msg_1', role: 'assistant', content: [{ type: 'text', text: 'Hello from the mock Anthropic API.' }] }, uuid: 'assistant-1', timestamp: '2026-10-11T12:35:37.393Z', sessionId },
		{ parentUuid: 'assistant-1', isSidechain: false, type: 'attachment', attachment: { type: 'prompt_snapshot' }, uuid: 'att-2', sessionId },
		{ type: 'last-prompt', lastPrompt: 'Say hello', leafUuid: 'att-2', sessionId },
		{ parentUuid: null, logicalParentUuid: 'att-2', isSidechain: false, type: 'system', subtype: 'compact_boundary', content: 'Conversation compacted', isMeta: false, timestamp: '2026-10-11T12:39:52.811Z', uuid: 'boundary', level: 'info', compactMetadata: { trigger: 'manual', preTokens: 70030, postTokens: 1103 }, sessionId },
		{ parentUuid: 'boundary', isSidechain: false, type: 'user', message: { role: 'user', content: summary }, isVisibleInTranscriptOnly: true, isCompactSummary: true, uuid: 'summary', timestamp: '2026-10-11T12:39:52.811Z', sessionId },
		{ parentUuid: 'summary', isSidechain: false, type: 'user', message: { role: 'user', content: '<local-command-caveat>Caveat: The messages below were generated by the user while running local commands.</local-command-caveat>' }, isMeta: true, uuid: 'caveat', sessionId },
		{ parentUuid: 'caveat', isSidechain: false, type: 'user', message: { role: 'user', content: '<command-name>/compact</command-name>\n            <command-message>compact</command-message>\n            <command-args></command-args>' }, uuid: 'command', sessionId },
		{ parentUuid: 'command', isSidechain: false, type: 'user', message: { role: 'user', content: '<local-command-stdout>Compacted </local-command-stdout>' }, uuid: 'stdout', sessionId },
		{ parentUuid: 'stdout', isSidechain: false, type: 'user', message: { role: 'user', content: [{ type: 'text', text: 'Say goodbye' }] }, uuid: 'request_2', timestamp: '2026-10-11T12:41:00.000Z', sessionId },
		{ parentUuid: 'request_2', isSidechain: false, type: 'assistant', message: { id: 'msg_2', role: 'assistant', content: [{ type: 'text', text: 'Goodbye.' }] }, uuid: 'assistant-2', timestamp: '2026-10-11T12:41:01.000Z', sessionId },
	].map(record => JSON.stringify(record)).join('\n') + '\n{"partly written';

	function sdkMessage(type: SessionMessage['type'], uuid: string, message: unknown, flags?: object): SessionMessage {
		return { type, uuid, session_id: sessionId, message, parent_tool_use_id: null, parent_agent_id: null, ...flags };
	}

	/** What the SDK's `getSessionMessages` returns for {@link transcript}: the chain from the boundary on, the boundary without its subtype. */
	const sdkMessages: SessionMessage[] = [
		sdkMessage('system', 'boundary', undefined),
		sdkMessage('user', 'summary', { role: 'user', content: summary }, { isCompactSummary: true, is_meta: true }),
		sdkMessage('user', 'command', { role: 'user', content: '<command-name>/compact</command-name>' }, { isCompletedLocalCommand: true }),
		sdkMessage('user', 'stdout', { role: 'user', content: '<local-command-stdout>Compacted </local-command-stdout>' }, { isCompletedLocalCommand: true }),
		sdkMessage('user', 'request_2', { role: 'user', content: [{ type: 'text', text: 'Say goodbye' }] }),
		sdkMessage('assistant', 'assistant-2', { id: 'msg_2', role: 'assistant', content: [{ type: 'text', text: 'Goodbye.' }] }),
	];

	test('replays the turns before a compaction, then the compaction notice, without the summary', () => {
		assert.strictEqual(startsAtCompaction(sdkMessages), true);
		const messages = expandCompactedHistory(sdkMessages, parseClaudeTranscript(transcript));
		const turns = mapSessionMessagesToTurns(messages, URI.parse('claude:/a24324bf'), new NullLogService());

		assert.deepStrictEqual(turns.map(turn => ({
			id: turn.id,
			text: turn.message.text,
			parts: turn.responseParts.map(part => part.kind === ResponsePartKind.Markdown || part.kind === ResponsePartKind.SystemNotification ? `${part.kind}: ${part.content}` : part.kind),
		})), [
			{ id: 'request_1', text: 'Say hello', parts: [`${ResponsePartKind.Markdown}: Hello from the mock Anthropic API.`, `${ResponsePartKind.SystemNotification}: Conversation compacted: older messages were summarized.`] },
			{ id: 'request_2', text: 'Say goodbye', parts: [`${ResponsePartKind.Markdown}: Goodbye.`] },
		]);
	});
});
